// The house gradient, orange through pink to violet, deepened just enough that
// the white marks keep at least a 3:1 contrast on every tile.
const SWEEP_ORANGE = "#cf711a"
const SWEEP_PINK = "#d76797"
const SWEEP_VIOLET = "#9362e4"
/** Share of the sweep that runs from orange to pink. Pink to violet takes the rest. */
const SWEEP_PINK_AT = 0.4
/** Where the sweep starts: the top left, in degrees clockwise from the right. */
const SWEEP_START = 225

/**
 * The direction of every tile from the centre at rest, in degrees clockwise
 * from the right. The honeycomb puts the first tile in the centre, then fills
 * ring by ring, each ring starting on the right and walking round clockwise.
 */
function restingAngles(count: number) {
  const angles = [0]
  for (let ring = 1; angles.length < count; ring++) {
    for (let step = 0; step < ring * 6 && angles.length < count; step++) {
      angles.push((step / (ring * 6)) * 360)
    }
  }
  return angles
}

/**
 * Tints a tile by its direction from the centre, so every ring sweeps from
 * orange at the top left, through pink, to violet at the bottom right, like
 * the centre tile itself.
 */
function sweepTint(angle: number) {
  const turn = (((angle - SWEEP_START) % 360) + 360) % 360
  // 0 at the top left, 1 at the bottom right, whichever way round the ring.
  const share = Math.min(turn, 360 - turn) / 180
  if (share <= SWEEP_PINK_AT) {
    const pink = Math.round((share / SWEEP_PINK_AT) * 100)
    return `color-mix(in oklch, ${SWEEP_PINK} ${pink}%, ${SWEEP_ORANGE})`
  }
  const violet = Math.round(
    ((share - SWEEP_PINK_AT) / (1 - SWEEP_PINK_AT)) * 100
  )
  return `color-mix(in oklch, ${SWEEP_VIOLET} ${violet}%, ${SWEEP_PINK})`
}

// One tint per tile. The centre tile keeps the full house gradient instead.
const tints = restingAngles(apps.length + 1).map(sweepTint)

function BrandMark({ path }: { path: string }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="currentColor"
      aria-hidden="true"
      className="size-2/5"
    >
      <path d={path} />
    </svg>
  )
}

function WorkspaceMark() {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="currentColor"
      fillRule="evenodd"
      aria-hidden="true"
      className="size-4/7"
    >
      <path d="M12 3l7.8 4.5v9L12 21l-7.8-4.5v-9zm0 4.5L8.1 9.75v4.5L12 16.5l3.9-2.25v-4.5z" />
    </svg>
  )
}

function caption(count: number) {
  if (count === 0) {
    return "Press an app to add it"
  }
  return `${count} ${count === 1 ? "app" : "apps"} added to your workspace`
}

export default function IconHoneycombDemo3() {
  const [added, setAdded] = useState<string[]>([])
  const toggle = (name: string) =>
    setAdded((current) =>
      current.includes(name)
        ? current.filter((app) => app !== name)
        : [...current, name]
    )

  return (
    <section className="bg-background border-border text-foreground w-96 max-w-full rounded-xl border p-4">
      <h2 className="text-center text-sm font-semibold">
        Add an app to your workspace
      </h2>
      <IconHoneycomb
        iconSize={52}
        duration={0}
        className="my-2 h-64"
        aria-label="Apps you can add"
      >
        <span className="bg-linear-to-br/oklch from-[#e8801a] to-[#9c40ff] text-white">
          <WorkspaceMark />
          <span className="sr-only">Your workspace</span>
        </span>
        {apps.map(({ name, path }, index) => (
          <button
            key={name}
            type="button"
            aria-label={name}
            aria-pressed={added.includes(name)}
            onClick={() => toggle(name)}
            style={{ backgroundColor: tints[index + 1] }}
            className="text-white aria-pressed:ring-2 aria-pressed:ring-white aria-pressed:ring-inset"
          >
            <BrandMark path={path} />
          </button>
        ))}
      </IconHoneycomb>
      <output
        aria-live="polite"
        className="text-muted-foreground block text-center text-sm"
      >
        {caption(added.length)}
      </output>
    </section>
  )
}
